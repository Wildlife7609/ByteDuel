-- KingOfBots database schema (PostgreSQL)
-- Create tables locally: psql -d kob -U kob -f backendcloud/db/schema.sql
-- In deployment it is mounted into the postgres container's /docker-entrypoint-initdb.d/ and runs on first start

-- Table names are plural and set with @TableName on the entities (user is a reserved word in PostgreSQL and cannot be a table name)
CREATE TABLE users (
    id         INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username   VARCHAR(100) NOT NULL UNIQUE,
    password   VARCHAR(100) NOT NULL,
    photo      VARCHAR(1000),
    rating     INT NOT NULL DEFAULT 1500,
    win_count  INT NOT NULL DEFAULT 0,
    lose_count INT NOT NULL DEFAULT 0,
    draw_count INT NOT NULL DEFAULT 0
);

CREATE TABLE bots (
    id          INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     INT NOT NULL,
    title       VARCHAR(100),
    description VARCHAR(300),
    content     TEXT,
    language    VARCHAR(20) NOT NULL DEFAULT 'java', -- cpp / java / python / go
    create_time TIMESTAMP,
    update_time TIMESTAMP
);
CREATE INDEX idx_bots_user_id ON bots (user_id); -- list a user's bots

CREATE TABLE records (
    id          INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    a_id        INT,
    a_sx        INT,
    a_sy        INT,
    b_id        INT,
    b_sx        INT,
    b_sy        INT,
    a_steps     TEXT,
    b_steps     TEXT,
    map         TEXT,
    loser       VARCHAR(10),
    create_time TIMESTAMP
);
