-- KingOfBots 数据库结构（PostgreSQL）
-- 本地建表：psql -d kob -U kob -f backendcloud/db/schema.sql
-- 部署时放进 postgres 容器的 /docker-entrypoint-initdb.d/，第一次启动时自动建表

-- 表名统一用复数，实体类里用 @TableName 指定（user 本身也是 PostgreSQL 的保留字，不能当表名）
CREATE TABLE users (
    id         INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username   VARCHAR(100) NOT NULL UNIQUE,
    password   VARCHAR(100) NOT NULL,
    photo      VARCHAR(1000),
    rating     INT NOT NULL DEFAULT 1500,
    win_count  INT NOT NULL DEFAULT 0,
    lose_count INT NOT NULL DEFAULT 0,
    draw_count INT NOT NULL DEFAULT 0
);

CREATE TABLE bots (
    id          INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     INT NOT NULL,
    title       VARCHAR(100),
    description VARCHAR(300),
    content     TEXT,
    language    VARCHAR(20) NOT NULL DEFAULT 'java', -- cpp / java / python / go
    create_time TIMESTAMP,
    update_time TIMESTAMP
);
CREATE INDEX idx_bots_user_id ON bots (user_id); -- 按用户查 Bot 列表

CREATE TABLE records (
    id          INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    a_id        INT,
    a_sx        INT,
    a_sy        INT,
    b_id        INT,
    b_sx        INT,
    b_sy        INT,
    a_steps     TEXT,
    b_steps     TEXT,
    map         TEXT,
    loser       VARCHAR(10),
    create_time TIMESTAMP
);
